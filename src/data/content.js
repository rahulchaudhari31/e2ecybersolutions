export const getServiceBySlug = (slug) =>
  services.find((service) => service.slug === slug);

export const getGroupBySlug = (slug) =>
  serviceGroups.find((group) => group.slug === slug);

export const getRelatedServices = (service) => {
  const group = getGroupBySlug(service.group);
  if (!group) return [];
  return group.services.filter((item) => item.slug !== service.slug);
};
